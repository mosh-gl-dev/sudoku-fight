// Writes src/i18n/languageNamesIn.generated.ts: the name of every language of the app (LANGUAGES in
// src/i18n/languages.ts, all 19) in every language of the app, so the language picker can show "גרמנית" above
// "Deutsch" in Hebrew and "希伯来语" above "עברית" in Chinese (Moshe, 25.11.2026: a player who switched to
// Chinese by mistake must still find his own language). The names are CLDR's (Node's ICU, the dialect form:
// "Simplified Chinese", "Brazilian Portuguese"), as the first letter of an item in a list writes them (capital
// in the languages that have one), with the fixes in OVERRIDES below. Each language's own entry is its
// LANGUAGE_NAMES name, the one the picker shows under it, so the row of the app's own language has one line.
// The app can't ask the phone for them: Hermes has no Intl.DisplayNames (the country names' story,
// gen-country-names.ts). Run it again after LANGUAGES changes; src/i18n/__tests__/languageNamesIn.test.ts fails
// until every language has a name in every language. It needs a Node with full ICU (the default since Node 13).
//   npm run languages:names -w @sudoku-fight/mobile
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { type Language, LANGUAGE_NAMES, LANGUAGES } from '../src/i18n/languages';

/** CLDR names a menu would say otherwise, by the app language they are written in. */
const OVERRIDES: Partial<Record<Language, Partial<Record<Language, string>>>> = {
  // CLDR's "китайский, упрощенное письмо" reads as a note, not as a language in a list.
  // A Japanese menu brackets in full width (common:text.parenthetical), not CLDR's "ポルトガル語 (ブラジル)".
  ja: { 'pt-BR': 'ポルトガル語（ブラジル）' },
  ru: { 'zh-Hans':'Китайский (упрощённый)', 'zh-Hant': 'Китайский (традиционный)' },
  // "Tiếng Ý" is the Vietnamese name of Italian; "Tiếng Italy" is CLDR's rarer form.
  vi: { it: 'Tiếng Ý' },
  // An Indonesian menu names a language "Bahasa …" (as the app's own name, "Bahasa Indonesia"); CLDR's bare
  // "Inggris" is England. Polish is "Bahasa Polandia" (CLDR's "Polski" is the Polish word).
  id: { pl: 'Bahasa Polandia' },
};

/** Languages whose menus put "Bahasa" before every bare CLDR name. */
const BAHASA: ReadonlySet<Language> = new Set(['id']);

const capitalize = (name: string, lang: string): string =>
  name.charAt(0).toLocaleUpperCase(lang) + name.slice(1);

const table = {} as Record<Language, Record<Language, string>>;
for (const ui of LANGUAGES) {
  const names = new Intl.DisplayNames([ui], {
    type: 'language',
    languageDisplay: 'dialect',
    fallback: 'none',
  });
  // A Node with small ICU falls back to English for a locale it lacks: zh-Hant would quietly get English names.
  const resolved = names.resolvedOptions().locale;
  if (resolved !== ui)
    throw new Error(`ICU resolved ${ui} as ${resolved}: run this with a Node that has full ICU.`);
  const row = {} as Record<Language, string>;
  for (const lang of LANGUAGES) {
    const cldr = names.of(lang);
    if (!cldr || cldr === lang)
      throw new Error(`No ${ui} name for ${lang}: run this with a Node that has full ICU.`);
    const fixed = OVERRIDES[ui]?.[lang] ?? (BAHASA.has(ui) ? `Bahasa ${cldr}` : cldr);
    row[lang] = lang === ui ? LANGUAGE_NAMES[ui] : capitalize(fixed, ui);
  }
  // The language's own name from CLDR should be the one LANGUAGE_NAMES has; say so when it is not.
  const own = capitalize(
    OVERRIDES[ui]?.[ui] ?? (BAHASA.has(ui) ? `Bahasa ${names.of(ui)}` : names.of(ui)!),
    ui,
  );
  if (own !== LANGUAGE_NAMES[ui])
    console.warn(`${ui}: CLDR names itself "${own}", LANGUAGE_NAMES "${LANGUAGE_NAMES[ui]}"`);
  table[ui] = row;
}

/** A TypeScript string as Prettier writes it (single quotes). */
const quote = (value: string): string => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const key = (code: string): string => (/^[a-z]+$/.test(code) ? code : quote(code));

const body = LANGUAGES.map((ui) => {
  const entries = LANGUAGES.map((lang) => `    ${key(lang)}: ${quote(table[ui][lang])},`);
  return `  ${key(ui)}: {\n${entries.join('\n')}\n  },`;
}).join('\n');

const source = `// Generated by scripts/gen-language-names.ts (\`npm run languages:names\` in apps/mobile) from Node's ICU (CLDR).
// Do not edit: fix a name in the script's OVERRIDES and run it again (src/i18n/__tests__/languageNamesIn.test.ts).
import type { Language } from './languages';

/** Every language of the app by its name in every language of the app: LANGUAGE_NAMES_IN[app][language]. */
export const LANGUAGE_NAMES_IN: Readonly<Record<Language, Readonly<Record<Language, string>>>> = {
${body}
};
`;

const target = join(__dirname, '..', 'src', 'i18n', 'languageNamesIn.generated.ts');
writeFileSync(target, source);
console.log(`Wrote ${target} (${LANGUAGES.length} × ${LANGUAGES.length} names, ICU ${process.versions.icu})`);
