// Writes src/components/ambient/digitPaths.generated.ts: the outlines of the digits 1–9 in Rubik Bold, the board's
// digit font, as SVG path strings. The ambient digits behind the calm screens (D126, motion.md §4.13) draw them
// as Skia paths, so the app needs no Skia font and no TTF of its own for them.
//
// Each glyph is in units of 1/100 of the digits' height (the tallest of the nine, so they keep their relative
// sizes), with y growing DOWN and the origin at the glyph's "feet": the middle of its ink, on the baseline. A
// digit drawn at size s is scaled by s / 100, and it turns and squashes about its feet.
//
// No randomness, no dates: a re-run writes the same bytes.
//   node apps/mobile/scripts/gen-digit-paths.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadFont } from './lib/ttf.mjs';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'src', 'components', 'ambient', 'digitPaths.generated.ts');
const FONT = require.resolve('@expo-google-fonts/rubik/700Bold/Rubik_700Bold.ttf');

const DIGITS = ['1', '2', '3', '4', '5', '6', '7', '8', '9'];
const font = loadFont(FONT);

const points = (cmds) => cmds.flatMap((c) => (c[0] === 'Z' ? [] : chunk(c.slice(1))));
const chunk = (xs) => xs.flatMap((_, i) => (i % 2 ? [] : [[xs[i], xs[i + 1]]]));

const outlines = DIGITS.map((digit) => ({ digit, cmds: font.glyph(digit) }));
const bounds = outlines.map(({ cmds }) => {
  const pts = points(cmds);
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return { minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
});
// The tallest digit's ink above the baseline is 100 units.
const unit = 100 / Math.max(...bounds.map((b) => b.maxY));
const round = (v) => Math.round(v * 10) / 10;

const glyphs = outlines.map(({ digit, cmds }, i) => {
  const b = bounds[i];
  const cx = (b.minX + b.maxX) / 2;
  const x = (v) => round((v - cx) * unit);
  const y = (v) => round(-v * unit);
  const d = cmds
    .map((c) => {
      if (c[0] === 'Z') return 'Z';
      if (c[0] === 'Q') return `Q${x(c[1])} ${y(c[2])} ${x(c[3])} ${y(c[4])}`;
      return `${c[0]}${x(c[1])} ${y(c[2])}`;
    })
    .join('');
  return {
    digit: Number(digit),
    d,
    width: round((b.maxX - b.minX) * unit),
    // Ink above the baseline, and the overshoot under it (the round digits), in the same units.
    top: round(b.maxY * unit),
    descent: round(Math.max(0, -b.minY) * unit),
  };
});

/** A glyph as Prettier writes it (the file is checked in formatted, and a re-run must not change it). */
const literal = (g) =>
  `  {\n    digit: ${g.digit},\n    d: '${g.d}',\n    width: ${g.width},\n    top: ${g.top},\n    descent: ${g.descent},\n  },\n`;

const body = `/* Generated by apps/mobile/scripts/gen-digit-paths.mjs from Rubik Bold (@expo-google-fonts/rubik). Do not edit. */

/**
 * A digit's outline: an SVG path in units of 1/100 of the digits' height, y down, its origin at the glyph's feet
 * (the middle of its ink, on the baseline). \`width\` is its ink's width, \`top\` how far its ink rises above the
 * baseline and \`descent\` how far the round digits dip under it, in the same units.
 */
export interface DigitPath {
  digit: number;
  d: string;
  width: number;
  top: number;
  descent: number;
}

/** The units of a path: a digit drawn \`size\` dp tall is scaled by size / DIGIT_UNITS. */
export const DIGIT_UNITS = 100;

/** The digits 1–9, in order. */
export const DIGIT_PATHS: readonly DigitPath[] = [
${glyphs.map(literal).join('')}];
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
